#!/usr/bin/env node
// make-winrar-sample.mjs - makes the evidence for examples/winrar with the REAL WinRAR tools installed on this machine:
//   1. Rar.exe writes a tiny RAR5 archive (stored, one file),
//   2. kit/rar5.js parses it and rebuilds it from the published format: the bytes must be identical,
//   3. UnRAR.exe tests and extracts the archive that kit/rar5.js built: it must accept it and give back the original file.
// Everything is recorded in examples/winrar/data.js, which the spec reads. Run it again with another WinRAR to refresh the evidence.
//
//   node scripts/make-winrar-sample.mjs            (WinRAR in C:/Program Files/WinRAR, or RAR_DIR=...)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), dir = process.env.RAR_DIR || 'C:/Program Files/WinRAR';
const RAR = path.join(dir, 'Rar.exe'), UNRAR = path.join(dir, 'UnRAR.exe');
if (!fs.existsSync(RAR) || !fs.existsSync(UNRAR)) { console.error('no encuentro Rar.exe / UnRAR.exe en ' + dir + ' (RAR_DIR=...)'); process.exit(1); }
const ctx = vm.createContext({ console, TextEncoder, TextDecoder }); ctx.window = ctx; vm.runInContext(fs.readFileSync(path.join(root, 'kit/rar5.js'), 'utf8'), ctx, { filename: 'kit/rar5.js' }); const R = ctx.MX.rar5;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mx-rar-')), content = 'Hello, WinRAR!', run = (exe, args, cwd) => spawnSync(exe, args, { cwd, encoding: 'utf8' });
fs.writeFileSync(path.join(tmp, 'hello.txt'), content, 'ascii');
const banner = (run(RAR, [], tmp).stdout || '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean)[0] || '';
const made = run(RAR, ['a', '-ma5', '-m0', '-ep', '-idq', 'hello.rar', 'hello.txt'], tmp); if (made.status !== 0) { console.error('Rar.exe fallo:', made.stdout, made.stderr); process.exit(1); }
const real = Uint8Array.from(fs.readFileSync(path.join(tmp, 'hello.rar'))), parsed = R.parse(real);
const fileBlk = parsed.blocks.find((b) => b.type === 2), timeRec = fileBlk.fields.find((f) => f.name === 'extra record' && /file time/.test(f.text)), mtime = Array.from(real.slice(timeRec.start + 3, timeRec.start + 11));
const built = R.build({ name: 'hello.txt', data: R.ascii(content), mtime }), identical = R.hex(built) === R.hex(real);
fs.writeFileSync(path.join(tmp, 'built.rar'), built);
const t = run(UNRAR, ['t', '-idq', 'built.rar'], tmp), outDir = path.join(tmp, 'out'); fs.mkdirSync(outDir);
const x = run(UNRAR, ['x', '-y', '-idq', 'built.rar', outDir + path.sep], tmp), got = fs.existsSync(path.join(outDir, 'hello.txt')) ? fs.readFileSync(path.join(outDir, 'hello.txt'), 'ascii') : null;
const sample = {
  tool: 'Rar.exe and UnRAR.exe from WinRAR on this machine', version: banner.replace(/\s{2,}/g, '  ').trim(), command: 'Rar.exe a -ma5 -m0 -ep hello.rar hello.txt', generated: new Date().toISOString().slice(0, 10),
  content, hex: R.hex(real), size: real.length, mtime: R.hex(mtime), headersOk: parsed.ok,
  rebuilt: { identical, bytes: built.length },
  unrar: { testExit: t.status, extractExit: x.status, extractedEqual: got === content },
};
fs.mkdirSync(path.join(root, 'examples/winrar'), { recursive: true });
fs.writeFileSync(path.join(root, 'examples/winrar/data.js'), '// generated by scripts/make-winrar-sample.mjs from the real WinRAR tools: do not edit\nwindow.WINRAR_SAMPLE = ' + JSON.stringify(sample, null, 2) + ';\n');
fs.mkdirSync(path.join(root, 'data/winrar'), { recursive: true }); fs.copyFileSync(path.join(tmp, 'hello.rar'), path.join(root, 'data/winrar/hello.rar')); fs.writeFileSync(path.join(root, 'data/winrar/hello.txt'), content);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(sample.version + '\narchive: ' + sample.size + ' bytes, headers ok: ' + parsed.ok + '\nrebuilt from the format: ' + (identical ? 'IDENTICAL, ' + built.length + ' of ' + real.length + ' bytes' : 'DIFFERENT') + '\nUnRAR test exit ' + t.status + ', extract exit ' + x.status + ', file back equal: ' + (got === content));
process.exit(identical && t.status === 0 && x.status === 0 && got === content ? 0 : 1);
